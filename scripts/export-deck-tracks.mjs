/**
 * Generate the Unreal deck-motion constants from the web source of truth.
 *
 *   node scripts/export-deck-tracks.mjs
 *
 * Most of the deck choreography is a handful of linear coefficients, and those
 * are written once, by hand, in RhineDeckMotion.cpp right next to the comment
 * naming the web line they mirror. What is *not* safe to retype is the geometry
 * the C++ has no other way to know: the five insert layers' depths and rest
 * poses, and the package's rest height. Those are emitted here from
 * src/ssh/deck-motion.ts into RhineDeckTracksData.h, so a web-side tweak cannot
 * leave Unreal with stale numbers.
 *
 * Fails loudly if a layer disappears or the module stops evaluating.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulePath = path.join(root, "src", "ssh", "deck-motion.ts");
const { SCREEN, DECK_PARTS, DECK_REST_Y, DECK_OPEN_SECONDS, DECK_CLOSE_SECONDS, deckPose } =
  await import(pathToFileURL(modulePath).href);

// The insert stack is the five DECK_PARTS layers; the four movable package
// layers are computed in C++ because their motion is what the port is about.
const ORDER = DECK_PARTS.map(part => part.id);
const pose = deckPose(1);

const literal = value => {
  if (!Number.isFinite(value)) throw new Error(`deck-motion produced a non-finite value: ${value}`);
  const text = String(Number(value.toPrecision(17)));
  return /[.e]/.test(text) ? text : `${text}.0`;
};

const rows = (values, columns) => values
  .map(id => `    { ${columns.map(column => literal(column(id))).join(", ")} },`)
  .join("\n");

const header = `// Generated by scripts/export-deck-tracks.mjs from src/ssh/deck-motion.ts. Do not edit by hand.
// Web units throughout: the Unreal port converts exactly once, in
// FRhineDeckMotion::WebToUnreal, so nothing here needs 100x arithmetic.
#pragma once

#include "CoreMinimal.h"

namespace RhineDeckTracks {
/** Screen anchor (art/build_terminal.py). */
inline constexpr double ScreenWidth = ${literal(SCREEN.width)};
inline constexpr double ScreenHeight = ${literal(SCREEN.height)};
inline constexpr double ScreenY = ${literal(SCREEN.y)};
inline constexpr double ScreenZ = ${literal(SCREEN.z)};

/** Rest height of the package: art/build_archive.py puts every shell at z=1.85. */
inline constexpr double RestY = ${literal(DECK_REST_Y)};
/** Seconds the deck takes to separate; the close is deliberately quicker. */
inline constexpr double OpenSeconds = ${literal(DECK_OPEN_SECONDS)};
inline constexpr double CloseSeconds = ${literal(DECK_CLOSE_SECONDS)};

/** The static insert stack, in DECK_PARTS order. Never moves. */
inline constexpr int32 InsertCount = ${ORDER.length};
inline constexpr const TCHAR* InsertIds[InsertCount] = {
${ORDER.map(id => `    TEXT("${id}"),`).join("\n")}
};
/** Layer depth (web Z) of each insert, for reference and for the log line. */
inline constexpr double InsertZ[InsertCount] = {
${ORDER.map(id => `    ${literal(DECK_PARTS.find(part => part.id === id).z)},`).join("\n")}
};
/** Rest pose (web X, Y, Z) of each insert, straight from deckPose(). */
inline constexpr double InsertPosition[InsertCount][3] = {
${rows(ORDER, [id => pose.parts[id].position.x, id => pose.parts[id].position.y, id => pose.parts[id].position.z])}
};

/** Index into InsertIds, or INDEX_NONE. */
inline int32 InsertIndex(const FString& Id) {
    for (int32 Index = 0; Index < InsertCount; ++Index) {
        if (Id == InsertIds[Index]) return Index;
    }
    return INDEX_NONE;
}
}
`;

writeFileSync(path.join(root, "prototypes", "unreal", "Source", "RhineLabViewer", "RhineDeckTracksData.h"), header);
console.log(`RHINE_DECK_TRACKS ${ORDER.length} insert layers, ${ORDER.length * 6} coefficients`);
